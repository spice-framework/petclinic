const spiceTool = "github.com/spice-framework/spice/cmd/spice"

func TestPetclinicDevelopmentWorkflowKeepsLastKnownGoodAndRestarts(
	t *testing.T,
) {
	root := copyDevelopmentModule(t)
	mainPath := filepath.Join(root, "main.go")
	original, err := os.ReadFile(mainPath) // #nosec G304 -- test-owned root.
	if err != nil {
		t.Fatalf("ReadFile(main.go) error = %v", err)
	}

	output := newNotifyingBuffer()
	command := exec.Command( // #nosec G204,G702 -- fixed repository-owned command.
		"go",
		"tool",
		spiceTool,
		"dev",
		"--target=Petclinic",
		"--poll=20ms",
		"--quiet=20ms",
		"--max-delay=100ms",
		"--stop-timeout=10s",
		".",
		"./memory",
		"./model",
		"./owner",
		"./presentation",
		"./system",
		"./vet",
	)
	command.Dir = root
	command.Env = developmentEnvironment()
	command.Stdout = output
	command.Stderr = output
	configureProcessTree(command)
	if err := command.Start(); err != nil {
		t.Fatalf("start spice dev: %v", err)
	}
	done := make(chan error, 1)
	go func() { done <- command.Wait() }()
	stopped := false
	t.Cleanup(func() {
		if stopped {
			return
		}
		stopProcessTree(t, command, done)
	})

	waitForText(t, output, "application started (revision 1)")
	waitForText(t, output, `"msg":"Spice application starting"`)

	broken := strings.Replace(
		string(original),
		"// @Application",
		"// @Application\n// @Unknown",
		1,
	)
	if err := os.WriteFile(mainPath, []byte(broken), 0o600); err != nil {
		t.Fatalf("WriteFile(broken main.go) error = %v", err)
	}
	waitForText(t, output, "revision 2 failed")
	waitForText(t, output, "last-known-good revision 1")

	if err := os.WriteFile(mainPath, original, 0o600); err != nil {
		t.Fatalf("WriteFile(fixed main.go) error = %v", err)
	}
	revision := waitForRevision(t, output, "application started (revision ", 3)
	waitForText(
		t,
		output,
		"graceful restart requested for revision "+strconv.Itoa(revision),
	)

	stopProcessTree(t, command, done)
	stopped = true
	assertSourceAndGeneratedOutput(t, root, original, output.String())
}

func copyDevelopmentModule(t *testing.T) string {
	t.Helper()
	repository, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("resolve repository root: %v", err)
	}
	destination := t.TempDir()
	for _, directory := range []string{
		"memory",
		"model",
		"owner",
		"presentation",
		"system",
		"vet",
	} {
		if err := os.CopyFS(
			filepath.Join(destination, directory),
			os.DirFS(filepath.Join(repository, directory)),
		); err != nil {
			t.Fatalf("copy Petclinic %s: %v", directory, err)
		}
	}
	for _, name := range []string{"go.mod", "go.sum", "main.go"} {
		content, err := os.ReadFile( // #nosec G304 -- repository-owned fixture.
			filepath.Join(repository, name),
		)
		if err != nil {
			t.Fatalf("read Petclinic %s: %v", name, err)
		}
		if err := os.WriteFile(
			filepath.Join(destination, name),
			content,
			0o600,
		); err != nil {
			t.Fatalf("write Petclinic %s: %v", name, err)
		}
	}
	return destination
}

func developmentEnvironment() []string {
	overrides := map[string]string{
		"GOFLAGS":                 "-mod=mod",
		"GOPROXY":                 "off",
		"GOTOOLCHAIN":             "local",
		"GOWORK":                  "off",
		"SPICE_PETCLINIC_ADDRESS": "127.0.0.1:0",
	}
	result := make([]string, 0, len(os.Environ())+len(overrides))
	for _, entry := range os.Environ() {
		key, _, found := strings.Cut(entry, "=")
		if !found {
			continue
		}
		if _, replaced := overrides[strings.ToUpper(key)]; !replaced {
			result = append(result, entry)
		}
	}
	for key, value := range overrides {
		result = append(result, key+"="+value)
	}
	return result
}

func assertSourceAndGeneratedOutput(
	t *testing.T,
	root string,
	original []byte,
	output string,
) {
	t.Helper()
	actual, err := os.ReadFile( // #nosec G304 -- test-owned root.
		filepath.Join(root, "main.go"),
	)
	if err != nil {
		t.Fatalf("ReadFile(restored main.go) error = %v", err)
	}
	if !bytes.Equal(actual, original) ||
		!bytes.Contains(actual, []byte("// @Application")) {
		t.Fatal("spice dev changed the handwritten application source")
	}
	mainUnit, err := os.ReadFile( // #nosec G304 -- test-owned root.
		filepath.Join(
			root,
			"internal",
			"spicegen",
			"petclinic",
			"sources",
			"_root",
			"main_spice_gen.go",
		),
	)
	if err != nil {
		t.Fatalf("ReadFile(generated main source unit) error = %v", err)
	}
	if !strings.HasPrefix(
		string(mainUnit),
		"//go:build !spice_generate\n\n"+
			"// Code generated by Spice. DO NOT EDIT.\n",
	) || !strings.Contains(string(mainUnit), ` = "petclinic"`) {
		t.Fatalf("generated main source unit is not canonical:\n%s", mainUnit)
	}
	for _, formerFailure := range []string{
		"invalid character U+0040 '@'",
		"expected declaration, found 'ILLEGAL'",
		"undefined: spiceMain",
		"gocommand-",
	} {
		if strings.Contains(output, formerFailure) {
			t.Fatalf("spice dev repeated %q:\n%s", formerFailure, output)
		}
	}
}

type notifyingBuffer struct {
	mu      sync.Mutex
	buffer  bytes.Buffer
	updated chan struct{}
}

func newNotifyingBuffer() *notifyingBuffer {
	return &notifyingBuffer{updated: make(chan struct{}, 1)}
}

func (buffer *notifyingBuffer) Write(content []byte) (int, error) {
	buffer.mu.Lock()
	written, err := buffer.buffer.Write(content)
	buffer.mu.Unlock()
	select {
	case buffer.updated <- struct{}{}:
	default:
	}
	return written, err
}

func (buffer *notifyingBuffer) String() string {
	buffer.mu.Lock()
	defer buffer.mu.Unlock()
	return buffer.buffer.String()
}

func waitForText(t *testing.T, buffer *notifyingBuffer, expected string) {
	t.Helper()
	timeout := time.NewTimer(90 * time.Second)
	defer timeout.Stop()
	for {
		if strings.Contains(buffer.String(), expected) {
			return
		}
		select {
		case <-buffer.updated:
		case <-timeout.C:
			t.Fatalf("timed out waiting for %q\n%s", expected, buffer.String())
		}
	}
}

func waitForRevision(
	t *testing.T,
	buffer *notifyingBuffer,
	prefix string,
	minimum int,
) int {
	t.Helper()
	timeout := time.NewTimer(90 * time.Second)
	defer timeout.Stop()
	for {
		if revision := matchingRevision(buffer.String(), prefix, minimum); revision != 0 {
			return revision
		}
		select {
		case <-buffer.updated:
		case <-timeout.C:
			t.Fatalf(
				"timed out waiting for %s%d+)\n%s",
				prefix,
				minimum,
				buffer.String(),
			)
		}
	}
}

func matchingRevision(output, prefix string, minimum int) int {
	for remainder := output; ; {
		_, after, found := strings.Cut(remainder, prefix)
		if !found {
			return 0
		}
		digits, rest, found := strings.Cut(after, ")")
		if found {
			revision, err := strconv.Atoi(digits)
			if err == nil && revision >= minimum {
				return revision
			}
		}
		remainder = after
		if found {
			remainder = rest
		}
	}
}

func TestMatchingRevision(t *testing.T) {
	t.Parallel()

	for _, test := range []struct {
		name    string
		output  string
		minimum int
		want    int
	}{
		{name: "matching", output: "application started (revision 4)", minimum: 3, want: 4},
		{name: "below minimum", output: "application started (revision 2)", minimum: 3},
		{name: "malformed", output: "application started (revision next)", minimum: 3},
		{name: "later match", output: "application started (revision 2)\napplication started (revision 5)", minimum: 3, want: 5},
	} {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			if got := matchingRevision(test.output, "application started (revision ", test.minimum); got != test.want {
				t.Fatalf("matchingRevision() = %d, want %d", got, test.want)
			}
		})
	}
}
